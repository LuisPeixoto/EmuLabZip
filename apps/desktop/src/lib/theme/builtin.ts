/** The colours a theme gets for anything it leaves out. */
export function baseColors(base: Base): Record<string, string> {
  return { ...(base === "dark" ? CLASSIC_DARK : DAYLIGHT) };
}

function theme(id: string, name: string, base: Base, description: string, colors: Record<string, string>): Theme {
  return {
    schema: 1,
    id,
    name,
    author: "EmuLabZip",
    description,
    base,
    colors: { ...baseColors(base), ...colors },
    fonts: { ...DEFAULT_FONTS },
    shape: { radius: 1 },
  };
}

