//! `docs/mcp-tools.md` is written from what the server offers, so it cannot drift. Run with `UPDATE_MCP_DOCS=1` to rewrite it.

mod common;

use common::Server;
use serde_json::{Value, json};

fn first_sentence(text: &str) -> String {
    let text = text.trim();
    match text.find(". ") {
        Some(i) => text[..=i].to_string(),
        None => text.to_string(),
    }
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn arguments(tool: &Value) -> String {
    let schema = &tool["inputSchema"];
    let required: Vec<&str> =
        schema["required"].as_array().map(|r| r.iter().filter_map(|v| v.as_str()).collect()).unwrap_or_default();
    let Some(props) = schema["properties"].as_object() else { return "none".into() };
    if props.is_empty() {
        return "none".into();
    }
    props
        .keys()
        .filter(|k| *k != "device" || required.contains(&"device"))
        .map(|k| if required.contains(&k.as_str()) { format!("`{k}`") } else { format!("`{k}`?") })
        .collect::<Vec<_>>()
        .join(", ")
}

fn kind(tool: &Value) -> &'static str {
    let a = &tool["annotations"];
    if a["destructiveHint"] == true {
        "Asks first"
    } else if a["readOnlyHint"] == true {
        "Reads"
    } else {
        "Changes"
    }
}

/// The tools by area, in the order a person would look for them.
fn area(name: &str) -> &'static str {
    let starts = |p: &[&str]| p.iter().any(|p| name.starts_with(p));
    if starts(&["net_", "analytics_", "openapi_"]) {
        "Network"
    } else if starts(&["watch_"]) {
        "Live watches"
    } else if starts(&["session_", "list_sessions", "delete_session"]) {
        "Sessions"
    } else if starts(&["read_database", "read_preferences", "storage_", "list_files", "read_file", "write_file"]) {
        "App data"
    } else if starts(&["list_crashes", "get_crash", "symbolicate", "list_mappings", "add_mapping", "remove_mapping"]) {
        "Crashes"
    } else if starts(&["record_trace", "trace_", "list_traces", "perf_", "memory_", "measure_", "analyze_heap"]) {
        "Performance"
    } else if starts(&[
        "audit_",
        "analyze_package",
        "diff_packages",
        "package_budget",
        "check_text",
        "check_link",
        "simulate_",
        "visual_",
        "i18n_",
        "get_layout",
    ]) {
        "Quality"
    } else if starts(&["webview_", "flutter_", "react_", "detect_frameworks"]) {
        "Frameworks and web pages"
    } else if starts(&[
        "flow_",
        "list_flows",
        "play_flow",
        "tap",
        "swipe",
        "input_text",
        "press_key",
        "launch_app",
        "open_url",
        "link_history",
        "verify_app_links",
        "forget_link",
        "remove_flow",
    ]) {
        "Input, flows and links"
    } else if starts(&["control_", "run_plugin", "list_plugins"]) {
        "Device controls"
    } else if starts(&[
        "save_state",
        "restore_state",
        "list_states",
        "diff_state",
        "list_emulator",
        "save_emulator",
        "load_emulator",
        "delete_emulator",
        "wipe_",
        "delete_device",
        "create_device",
        "device_options",
        "boot_",
        "shutdown_",
        "list_all_devices",
        "compare_devices",
        "list_devices",
        "device_info",
        "list_apps",
    ]) {
        "Devices and state"
    } else if starts(&["screenshot", "read_logs", "create_bug_report"]) {
        "Screen, logs and reports"
    } else {
        "Other"
    }
}

fn render() -> String {
    let mut s = Server::start_session_with(&["--allow-writes"], Some("accept"));
    let tools = s.call(2, "tools/list", json!({}));
    let tools = tools["result"]["tools"].as_array().unwrap().clone();
    let prompts = s.call(3, "prompts/list", json!({}))["result"]["prompts"].as_array().unwrap().clone();
    let resources = s.call(4, "resources/list", json!({}))["result"]["resources"].as_array().unwrap().clone();
    let templates =
        s.call(5, "resources/templates/list", json!({}))["result"]["resourceTemplates"].as_array().unwrap().clone();

    let mut out = String::new();
    out.push_str("# MCP reference\n\n");
    out.push_str("<!-- Generated by `UPDATE_MCP_DOCS=1 cargo test -p emulabzip-cli --test mcp_reference`. Do not edit by hand. -->\n\n");
    out.push_str(&format!(
        "{} tools, {} prompts and {} resources, as `emulabzip mcp --allow-writes` offers them. Without `--allow-writes` the tools marked **Asks first** are not offered. See [MCP server](mcp.md) for how to connect and what is safe.\n\n",
        tools.len(),
        prompts.len(),
        resources.len() + templates.len()
    ));
    out.push_str("- **Reads** only looks.\n- **Changes** acts on a device or on EmuLabZip's own files, and can be put back.\n- **Asks first** destroys or rewrites data: only with `--allow-writes`, and each call asks the person to confirm.\n\n");
    out.push_str("Every tool that acts on a device also takes an optional `device` (an id or a name). An argument followed by `?` is optional.\n\n");

    let order = [
        "Screen, logs and reports",
        "Devices and state",
        "Input, flows and links",
        "Device controls",
        "Performance",
        "Quality",
        "Crashes",
        "Network",
        "Live watches",
        "Sessions",
        "App data",
        "Frameworks and web pages",
        "Other",
    ];
    for group in order {
        let mut rows: Vec<&Value> = tools.iter().filter(|t| area(t["name"].as_str().unwrap()) == group).collect();
        if rows.is_empty() {
            continue;
        }
        rows.sort_by_key(|t| t["name"].as_str().unwrap().to_string());
        out.push_str(&format!("## {group}\n\n| Tool | Does | Arguments | |\n|------|------|-----------|--|\n"));
        for t in rows {
            out.push_str(&format!(
                "| `{}` | {} | {} | {} |\n",
                t["name"].as_str().unwrap(),
                cell(&first_sentence(t["description"].as_str().unwrap_or(""))),
                cell(&arguments(t)),
                kind(t)
            ));
        }
        out.push('\n');
    }

    out.push_str("## Prompts\n\nReady-made plans an assistant can start from. Each names the tools to call.\n\n| Prompt | For | Arguments |\n|--------|-----|-----------|\n");
    for p in &prompts {
        let args = p["arguments"]
            .as_array()
            .map(|a| {
                a.iter()
                    .map(|x| {
                        if x["required"] == true {
                            format!("`{}`", x["name"].as_str().unwrap())
                        } else {
                            format!("`{}`?", x["name"].as_str().unwrap())
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(", ")
            })
            .unwrap_or_default();
        out.push_str(&format!(
            "| `{}` | {} | {} |\n",
            p["name"].as_str().unwrap(),
            cell(p["description"].as_str().unwrap_or("")),
            args
        ));
    }
    out.push_str("\n## Resources\n\nThings an assistant can read without calling a tool.\n\n| Address | Contains |\n|---------|----------|\n");
    for r in resources.iter().chain(templates.iter()) {
        let uri = r["uri"].as_str().or_else(|| r["uriTemplate"].as_str()).unwrap();
        out.push_str(&format!("| `{}` | {} |\n", uri, cell(r["description"].as_str().unwrap_or(""))));
    }
    out
}

#[test]
fn the_reference_matches_what_the_server_offers() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/mcp-tools.md");
    let made = render();
    if std::env::var_os("UPDATE_MCP_DOCS").is_some() {
        std::fs::write(&path, &made).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == made,
        "docs/mcp-tools.md is out of date: run `UPDATE_MCP_DOCS=1 cargo test -p emulabzip-cli --test mcp_reference`"
    );
}

#[test]
fn every_tool_is_in_an_area() {
    let mut s = Server::start_session_with(&["--allow-writes"], None);
    let tools = s.call(2, "tools/list", json!({}));
    let other: Vec<&str> = tools["result"]["tools"]
        .as_array()
        .unwrap()
        .iter()
        .map(|t| t["name"].as_str().unwrap())
        .filter(|n| area(n) == "Other")
        .collect();
    assert!(other.is_empty(), "these tools are in no area of the reference: {other:?}");
}
